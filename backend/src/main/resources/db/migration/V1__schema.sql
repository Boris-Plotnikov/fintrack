CREATE TABLE offices (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(3)   NOT NULL UNIQUE,
    name        VARCHAR(60)  NOT NULL
);

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(40)  NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    full_name     VARCHAR(80)  NOT NULL,
    role          VARCHAR(10)  NOT NULL,
    office_id     BIGINT REFERENCES offices (id)
);

CREATE TABLE accounts (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(80)   NOT NULL UNIQUE,
    type             VARCHAR(10)   NOT NULL,
    currency         VARCHAR(3)    NOT NULL,
    office_id        BIGINT        NOT NULL REFERENCES offices (id),
    owner_id         BIGINT        NOT NULL REFERENCES users (id),
    manager_id       BIGINT        NOT NULL REFERENCES users (id),
    opening_balance  NUMERIC(18,2) NOT NULL,
    tolerance        NUMERIC(18,2) NOT NULL,
    active           BOOLEAN       NOT NULL
);

CREATE TABLE categories (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  VARCHAR(60) NOT NULL UNIQUE,
    kind  VARCHAR(10) NOT NULL
);

CREATE TABLE exchange_rates (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    currency     VARCHAR(3)    NOT NULL,
    rate_to_eur  NUMERIC(18,6) NOT NULL,
    valid_from   DATE          NOT NULL,
    CONSTRAINT uq_rate UNIQUE (currency, valid_from)
);

CREATE TABLE shifts (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL REFERENCES users (id),
    office_id   BIGINT      NOT NULL REFERENCES offices (id),
    opened_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    closed_at   TIMESTAMP WITH TIME ZONE,
    status      VARCHAR(10) NOT NULL
);

CREATE TABLE transfers (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_account_id  BIGINT        NOT NULL REFERENCES accounts (id),
    to_account_id    BIGINT        NOT NULL REFERENCES accounts (id),
    amount           NUMERIC(18,2) NOT NULL,
    amount_received  NUMERIC(18,2) NOT NULL,
    status           VARCHAR(10)   NOT NULL,
    comment          VARCHAR(300),
    created_by       BIGINT        NOT NULL REFERENCES users (id),
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    decided_by       BIGINT REFERENCES users (id),
    decided_at       TIMESTAMP WITH TIME ZONE
);

CREATE TABLE operations (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind          VARCHAR(20)   NOT NULL,
    account_id    BIGINT        NOT NULL REFERENCES accounts (id),
    category_id   BIGINT REFERENCES categories (id),
    amount        NUMERIC(18,2) NOT NULL,
    currency      VARCHAR(3)    NOT NULL,
    rate_to_eur   NUMERIC(18,6) NOT NULL,
    amount_eur    NUMERIC(18,2) NOT NULL,
    description   VARCHAR(300)  NOT NULL,
    counterparty  VARCHAR(120),
    operation_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by    BIGINT        NOT NULL REFERENCES users (id),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    corrects_id   BIGINT REFERENCES operations (id),
    transfer_id   BIGINT REFERENCES transfers (id),
    shift_id      BIGINT REFERENCES shifts (id),
    source        VARCHAR(10)   NOT NULL
);
CREATE INDEX ix_operations_account ON operations (account_id);
CREATE INDEX ix_operations_at ON operations (operation_at);
CREATE INDEX ix_operations_corrects ON operations (corrects_id);

CREATE TABLE shift_counts (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shift_id          BIGINT        NOT NULL REFERENCES shifts (id),
    account_id        BIGINT        NOT NULL REFERENCES accounts (id),
    expected          NUMERIC(18,2) NOT NULL,
    counted           NUMERIC(18,2) NOT NULL,
    difference        NUMERIC(18,2) NOT NULL,
    within_tolerance  BOOLEAN       NOT NULL,
    comment           VARCHAR(300)
);

CREATE TABLE anomalies (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type             VARCHAR(25)  NOT NULL,
    severity         VARCHAR(10)  NOT NULL,
    message          VARCHAR(400) NOT NULL,
    operation_id     BIGINT REFERENCES operations (id),
    shift_id         BIGINT REFERENCES shifts (id),
    account_id       BIGINT REFERENCES accounts (id),
    status           VARCHAR(10)  NOT NULL,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    resolved_by      BIGINT REFERENCES users (id),
    resolution_note  VARCHAR(400)
);

CREATE TABLE audit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at          TIMESTAMP WITH TIME ZONE NOT NULL,
    user_id     BIGINT REFERENCES users (id),
    username    VARCHAR(40)  NOT NULL,
    action      VARCHAR(40)  NOT NULL,
    entity      VARCHAR(30)  NOT NULL,
    entity_id   BIGINT,
    details     VARCHAR(1000) NOT NULL
);
CREATE INDEX ix_audit_at ON audit_log (at);
